#!/usr/bin/env bun
// Builds worker/knowledge.md from the site's real content so the AI persona
// never goes stale. Run after changing any site content:
//
//   bun scripts/build-knowledge.mjs   (or: bun run ai:knowledge)
//
// It also emits worker/worker.deploy.js — a single self-contained worker file
// with everything inlined, for pasting into the Cloudflare dashboard.

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

import { projects as featuredProjects } from "../src/lib/projects-data.ts";
import { bucketList } from "../src/lib/bucket-list-data.ts";
import { getAllThoughts } from "../src/lib/thoughts-data.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const workerDir = join(root, "worker");
mkdirSync(workerDir, { recursive: true });

// --- Projects: union of the homepage "Actively Building" list (projects-data.ts)
// and the dedicated /projects page, which keeps its own hardcoded array.
function readProjectsPageArray() {
  const src = readFileSync(join(root, "src/app/projects/page.tsx"), "utf8");
  const marker = "const projects = [";
  const start = src.indexOf(marker);
  if (start === -1) throw new Error("Could not find projects array in src/app/projects/page.tsx");
  const slice = src.slice(start + "const projects = ".length);
  const end = slice.indexOf("];");
  if (end === -1) throw new Error("Could not find end of projects array in projects/page.tsx");
  return new Function(`return ${slice.slice(0, end + 1)}`)();
}

const byTitle = new Map();
for (const p of [...readProjectsPageArray(), ...featuredProjects]) {
  const key = p.title.toLowerCase().trim();
  const existing = byTitle.get(key);
  if (existing) {
    existing.link = existing.link || p.link;
  } else {
    byTitle.set(key, { title: p.title, description: p.description, link: p.link });
  }
}
const projectsSection = [...byTitle.values()]
  .map((p) => `- **${p.title}** — ${p.description}${p.link ? `\n  Link: ${p.link}` : ""}`)
  .join("\n");

const bucketSection = bucketList
  .map((b) => `${b.id}. ${b.text}${b.done ? " (done ✓)" : ""}${b.link ? ` — ${b.link}` : ""}`)
  .join("\n");

const thoughtsSection = getAllThoughts()
  .map((t) => `## ${t.title} (${t.date})\n\n${t.content.trim()}`)
  .join("\n\n");

// --- Assemble knowledge.md: static facts first, generated sections after
const staticMd = readFileSync(join(workerDir, "knowledge/static.md"), "utf8");
const knowledge = [
  "<!-- AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand.",
  "     Edit worker/knowledge/static.md or the site source, then rerun the script. -->",
  staticMd.trim(),
  "## Projects",
  projectsSection,
  "## Bucket List",
  bucketSection,
  "## Thoughts (blog posts, full text)",
  thoughtsSection || "(no posts yet)",
  "",
].join("\n\n");
writeFileSync(join(workerDir, "knowledge.md"), knowledge);
console.log(`✔ worker/knowledge.md (${(knowledge.length / 1024).toFixed(1)} KB, ${knowledge.split(/\s+/).length} words)`);

// --- Emit the dashboard-pasteable worker with knowledge + tweets inlined
const workerSrc = readFileSync(join(root, "worker.js"), "utf8");
const tweets = JSON.parse(readFileSync(join(workerDir, "tweets.json"), "utf8") || "[]");
let deploySrc = workerSrc
  .replace(
    'import knowledge from "./worker/knowledge.md";',
    `const knowledge = ${JSON.stringify(knowledge)};`,
  )
  .replace(
    'import tweets from "./worker/tweets.json";',
    `const tweets = ${JSON.stringify(tweets)};`,
  );
if (deploySrc === workerSrc) {
  throw new Error(
    "Could not inline imports into worker.js — did the import lines at the top change?",
  );
}
writeFileSync(join(workerDir, "worker.deploy.js"), deploySrc);
console.log(`✔ worker/worker.deploy.js (${(deploySrc.length / 1024).toFixed(1)} KB) — paste into the dashboard or deploy with wrangler`);
console.log(`✔ ${tweets.length} tweets inlined (run bun scripts/import-tweets.mjs <archive> to import your X archive)`);
